#!/bin/bash
# ci_post_clone.sh
#
# Xcode Cloud post-clone script.
# Selects the backend environment for this build. Each Xcode Cloud workflow
# sets APP_ENVIRONMENT to "beta" or "prod" (App Store Connect > Xcode Cloud >
# Workflow > Environment), and this script writes the matching build settings
# to Config/Environment.generated.xcconfig, which Config/App.xcconfig includes.
#
# The backend for each environment is in Config/Stages/<environment>.xcconfig.
# An environment with no such file builds an app with no backend.
#
# Optional: API_HOST, a bare host name that replaces the one in that file.
#
# Xcode Cloud sets CI_PRIMARY_REPOSITORY_PATH to the repo root.
# This script is located at: FinalApproach/ci_scripts/ci_post_clone.sh

set -euo pipefail

CONFIG_DIR="${CI_PRIMARY_REPOSITORY_PATH}/FinalApproach/Config"
GENERATED_PATH="${CONFIG_DIR}/Environment.generated.xcconfig"

echo "--- ci_post_clone: Selecting app environment ---"

# 1. Verify the environment variable is set to a known value
case "${APP_ENVIRONMENT:-}" in
    beta)
        DISPLAY_NAME="Approach Beta"
        ;;
    prod)
        DISPLAY_NAME="Final Approach"
        ;;
    "")
        echo "ERROR: APP_ENVIRONMENT environment variable is not set."
        echo "Set it to beta or prod in App Store Connect > Xcode Cloud > Workflow > Environment."
        exit 1
        ;;
    *)
        echo "ERROR: APP_ENVIRONMENT must be beta or prod, got: ${APP_ENVIRONMENT}"
        exit 1
        ;;
esac

# 2. Verify the target directory exists
if [ ! -d "${CONFIG_DIR}" ]; then
    echo "ERROR: Config directory does not exist: ${CONFIG_DIR}"
    exit 1
fi

# 3. Validate the optional host name so it cannot inject other build settings
API_HOST_VALUE="${API_HOST:-}"
if [[ ! "${API_HOST_VALUE}" =~ ^[A-Za-z0-9.-]*$ ]]; then
    echo "ERROR: API_HOST must be a bare host name such as api.example.com."
    exit 1
fi

# 4. Write the generated settings. A later line wins, so the stage's own
#    file comes first and anything set here replaces it.
{
    echo "// Generated by ci_scripts/ci_post_clone.sh. Do not commit."
    if [ -f "${CONFIG_DIR}/Stages/${APP_ENVIRONMENT}.xcconfig" ]; then
        echo "#include \"Stages/${APP_ENVIRONMENT}.xcconfig\""
    else
        echo "NOTE: No Stages/${APP_ENVIRONMENT}.xcconfig, so this build has no backend unless API_HOST is set." >&2
    fi
    echo "APP_ENVIRONMENT = ${APP_ENVIRONMENT}"
    echo "APP_DISPLAY_NAME = ${DISPLAY_NAME}"
    if [ -n "${API_HOST_VALUE}" ]; then
        echo "API_HOST = ${API_HOST_VALUE}"
    fi
} > "${GENERATED_PATH}"

echo "SUCCESS: ${APP_ENVIRONMENT} settings written to ${GENERATED_PATH}"
echo "--- ci_post_clone: Done ---"
